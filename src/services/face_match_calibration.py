"""Threshold calibration for face_match_service.

Computes FAR/FRR over labeled genuine/impostor pairs and picks a threshold
at a target FAR. NOT used at runtime — offline tool only.
"""
from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path
from typing import Iterable

import numpy as np

from src.services.face_match_service import FaceMatchService


@dataclass
class CalibrationResult:
    threshold: float
    far: float
    frr: float
    eer: float
    n_genuine: int
    n_impostor: int
    genuine_scores: list = field(default_factory=list)
    impostor_scores: list = field(default_factory=list)


def _load_bgr(path: Path) -> np.ndarray:
    import cv2
    img = cv2.imread(str(path))
    if img is None:
        raise FileNotFoundError(path)
    return img


def calibrate(
    genuine_pairs: Iterable[tuple[Path, Path]],
    impostor_pairs: Iterable[tuple[Path, Path]],
    service: FaceMatchService,
    target_far: float = 0.001,
) -> CalibrationResult:
    """Calibrate threshold at a target FAR (default 0.1%)."""
    genuine_scores, impostor_scores = [], []

    for a, b in genuine_pairs:
        try:
            genuine_scores.append(service.similarity(_load_bgr(a), _load_bgr(b)))
        except ValueError:
            continue  # skip pairs without exactly one face

    for a, b in impostor_pairs:
        try:
            impostor_scores.append(service.similarity(_load_bgr(a), _load_bgr(b)))
        except ValueError:
            continue

    if not genuine_scores or not impostor_scores:
        raise RuntimeError("not enough valid pairs to calibrate")

    g = np.array(genuine_scores)
    i = np.array(impostor_scores)

    # Candidate thresholds over the combined range
    candidates = np.unique(np.concatenate([g, i]))
    best = None
    for t in candidates:
        far = float((i >= t).mean())
        frr = float((g < t).mean())
        # First threshold where FAR <= target_far (strictest safe)
        if far <= target_far and best is None:
            best = (t, far, frr)
    if best is None:
        # Fall back to the threshold that minimizes |FAR - target_far|
        best = min(
            ((t, float((i >= t).mean()), float((g < t).mean())) for t in candidates),
            key=lambda x: abs(x[1] - target_far),
        )

    # EER: threshold where FAR ≈ FRR
    fars = np.array([(i >= t).mean() for t in candidates])
    frrs = np.array([(g < t).mean() for t in candidates])
    eer_idx = int(np.argmin(np.abs(fars - frrs)))
    eer = float((fars[eer_idx] + frrs[eer_idx]) / 2)

    return CalibrationResult(
        threshold=float(best[0]),
        far=best[1],
        frr=best[2],
        eer=eer,
        n_genuine=len(genuine_scores),
        n_impostor=len(impostor_scores),
        genuine_scores=genuine_scores,
        impostor_scores=impostor_scores,
    )


def report(result: CalibrationResult) -> str:
    return (
        f"Pairs: genuine={result.n_genuine} impostor={result.n_impostor}\n"
        f"Threshold@FAR={result.far:.4f}: {result.threshold:.4f} "
        f"(FRR={result.frr:.4f})\n"
        f"EER: {result.eer:.4f}"
    )


def save_threshold(result: CalibrationResult, path: Path = Path("configs/face_match_thresholds.yaml")):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        f"# Auto-generated by face_match_calibration.py\n"
        f"face_match:\n"
        f"  threshold: {result.threshold:.4f}\n"
        f"  far: {result.far:.6f}\n"
        f"  frr: {result.frr:.6f}\n"
        f"  eer: {result.eer:.6f}\n"
        f"  n_genuine: {result.n_genuine}\n"
        f"  n_impostor: {result.n_impostor}\n"
    )
